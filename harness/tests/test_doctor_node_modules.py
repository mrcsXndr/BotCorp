"""doctor `node_modules` + the daemon's "bot.yaml unreadable" cause.

A `git worktree remove` through a node_modules junction once emptied the live
checkout's node_modules; the daemon then skipped every bot with "bot.yaml
unreadable" and nothing named the cause.

Locked behaviour:
- cli/_deps.mjs depsVerdict(root): FAIL when <root>/node_modules is missing,
  empty (dotfiles only) or any package.json `dependencies` entry does not
  resolve from the root; the detail always ends "Fix: npm ci in <root>";
- cli/botcorp.mjs checks that BEFORE importing anything that needs
  node_modules: `doctor` then prints the FAIL check (text and --json) and every
  other command a one-line error, exit 1, never an ERR_MODULE_NOT_FOUND stack;
- daemon Get-BotConfig logs "bot.yaml unreadable: MODULE_NOT_FOUND '<pkg>'"
  with the same fix when the parser could not load a package.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ASSEMBLY = Path(__file__).resolve().parents[2]
DEPS = (ASSEMBLY / "cli" / "_deps.mjs").as_uri()

needs_node = pytest.mark.skipif(shutil.which("node") is None, reason="node not on PATH")
needs_pwsh = pytest.mark.skipif(sys.platform != "win32" or shutil.which("pwsh") is None or shutil.which("node") is None,
                                reason="Windows with pwsh and node on PATH")


def _verdict(root: Path) -> dict:
    script = f"const m = await import({json.dumps(DEPS)}); console.log(JSON.stringify(m.depsVerdict({json.dumps(str(root))})));"
    r = subprocess.run(["node", "--input-type=module", "-e", script], capture_output=True, text=True, timeout=60)
    assert r.returncode == 0, r.stderr
    return json.loads(r.stdout.strip().splitlines()[-1])


def _fake_pkg(nm: Path, name: str) -> None:
    d = nm / name
    d.mkdir(parents=True)
    (d / "package.json").write_text(json.dumps({"name": name, "version": "1.0.0", "main": "index.js"}), encoding="utf-8")
    (d / "index.js").write_text("module.exports = {};\n", encoding="utf-8")


def _checkout(tmp_path: Path) -> Path:
    """The CLI's own files + package.json, and an EMPTY node_modules (what the wipe left)."""
    ck = tmp_path / "ck"
    (ck / "cli").mkdir(parents=True)
    (ck / "daemon").mkdir()
    for f in (ASSEMBLY / "cli").glob("*.mjs"):
        shutil.copy2(f, ck / "cli" / f.name)
    for n in ("botyaml.mjs", "sync.mjs", "_common.ps1"):
        shutil.copy2(ASSEMBLY / "daemon" / n, ck / "daemon" / n)
    shutil.copy2(ASSEMBLY / "package.json", ck / "package.json")
    (ck / "node_modules").mkdir()
    (ck / "node_modules" / ".package-lock.json").write_text("{}", encoding="utf-8")
    return ck


@needs_node
def test_verdict_missing_empty_incomplete_and_ok(tmp_path):
    root = tmp_path / "root"
    root.mkdir()
    (root / "package.json").write_text(json.dumps({"dependencies": {"js-yaml": "^4", "zz-botcorp-dep": "1"}}), encoding="utf-8")
    fix = f"Fix: npm ci in {root}"

    v = _verdict(root)
    assert v["level"] == "FAIL" and "is missing" in v["detail"] and v["detail"].endswith(fix)
    assert sorted(v["missing"]) == ["js-yaml", "zz-botcorp-dep"]

    nm = root / "node_modules"
    nm.mkdir()
    (nm / ".package-lock.json").write_text("{}", encoding="utf-8")
    v = _verdict(root)
    assert v["level"] == "FAIL" and "is empty" in v["detail"] and v["detail"].endswith(fix)

    _fake_pkg(nm, "zz-botcorp-dep")
    v = _verdict(root)
    assert v["level"] == "FAIL" and "is incomplete (cannot resolve: js-yaml)" in v["detail"]
    assert "daemon skips every bot" in v["detail"] and v["missing"] == ["js-yaml"]

    _fake_pkg(nm, "js-yaml")
    v = _verdict(root)
    assert v["level"] == "PASS" and v["missing"] == [], v


@needs_node
def test_cli_on_a_wiped_node_modules_names_the_fix_not_a_stack(tmp_path):
    ck = _checkout(tmp_path)
    cli = str(ck / "cli" / "botcorp.mjs")
    env = {**os.environ, "BOTCORP_HOME": str(tmp_path / "rt"), "BOT_TG_MUTE": "1"}
    run = lambda *a: subprocess.run(["node", cli, *a], capture_output=True, text=True, timeout=60, env=env, cwd=str(ck))
    fix = f"Fix: npm ci in {ck}"

    r = run("doctor", "--json")
    assert r.returncode == 1, r.stderr
    checks = json.loads(r.stdout)
    assert [(c["level"], c["name"]) for c in checks] == [("FAIL", "node_modules")]
    assert "is empty" in checks[0]["detail"] and checks[0]["detail"].endswith(fix)

    r = run("doctor")
    assert r.returncode == 1 and "FAIL node_modules:" in r.stdout and fix in r.stdout
    assert "doctor: 1 checks, 1 FAIL" in r.stdout

    r = run("status")
    assert r.returncode == 1 and fix in r.stderr
    assert "MODULE_NOT_FOUND" not in r.stderr and "node:internal" not in r.stderr


@needs_pwsh
def test_daemon_logs_module_not_found_as_the_cause(tmp_path):
    ck = _checkout(tmp_path)
    (ck / "bots" / "zz").mkdir(parents=True)
    (ck / "bots" / "zz" / "bot.yaml").write_text("name: zz\n", encoding="utf-8")
    rt = tmp_path / "rt"
    script = f"$env:BOTCORP_HOME = '{rt}'\n. '{ck / 'daemon' / '_common.ps1'}'\n$c = Get-BotConfig -Bot zz\n\"null=$($null -eq $c)\""
    r = subprocess.run(["pwsh", "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-Command", script],
                       capture_output=True, text=True, timeout=120, cwd=str(ck))
    assert r.returncode == 0, r.stderr + r.stdout
    assert r.stdout.strip().splitlines()[-1] == "null=True"
    log = (rt / "logs" / "zz" / "daemon.log").read_text(encoding="utf-8-sig")
    assert "bot.yaml unreadable: MODULE_NOT_FOUND 'js-yaml'" in log, log
    assert f"Fix: npm ci in {ck}" in log, log
